  export function getTranslation(language, key) {
    const keys = key.split('.')
    let value = translations[language]
  
    for (const k of keys) {
      value = value?.[k]
    }
  
    return value ?? getFallback(key)
  }
  
  function getFallback(key) {
    const keys = key.split('.')
    let value = translations.en
  
    for (const k of keys) {
      value = value?.[k]
    }
  
    return value ?? key
  }
  
  export default translations